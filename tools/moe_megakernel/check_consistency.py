#!/usr/bin/env python3
"""Re-derive every load-bearing number from the CSVs and check the docs still agree.

Run this before committing. Numbers in prose go stale the moment data is re-collected,
and this folder has already shipped one docstring table that contradicted the script
printing it. Everything quoted in a .md should be reproducible from data/ by a few lines
of arithmetic; if it is not, it should not be quoted.

Exits non-zero if any check fails.
"""
import csv, glob, os, sys
from collections import defaultdict
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
os.chdir(HERE)


def mean_by(path, key, val):
    d = defaultdict(list)
    for r in csv.DictReader(open(path)):
        d[r[key]].append(float(r[val]))
    return {k: float(np.mean(v)) for k, v in d.items()}


def main():
    docs = "\n".join(open(f).read() for f in sorted(glob.glob("*.md")))
    checks = []

    # --- what a partitionable kernel costs --------------------------------
    m = mean_by("data/pin_vs_queue_qwen.csv", "case", "ms")
    q = m["queue"]
    pinned = min(v for k, v in m.items() if k.startswith("pinned"))
    checks += [
        ("queue latency (ms)", f"{q:.3f}"),
        ("persistent 1 blk/SM", f"{m['persistent_1blk_per_sm']/q-1:+.1%}"),
        ("persistent 2 blk/SM", f"{m['persistent_2blk_per_sm']/q-1:+.1%}"),
        ("best pinned split", f"{pinned/q-1:+.1%}"),
    ]

    # --- the clock sweep ---------------------------------------------------
    by = defaultdict(list)
    for r in csv.DictReader(open("data/b1_energy_qwen.csv")):
        by[int(r["clock"])].append(r)
    A = lambda c, k: float(np.mean([float(x[k]) for x in by[c]]))
    held = [c for c in sorted(by) if c > 0 and abs(c - A(c, "clock_med")) <= 7]
    best = min(held, key=lambda c: A(c, "energy_mj_per_layer"))
    checks += [
        ("energy-optimal clock (MHz)", str(best)),
        ("1050 MHz vs governor, energy", f"{A(1050,'energy_mj_per_layer')/A(-1,'energy_mj_per_layer')-1:+.1%}"),
        ("1050 MHz vs governor, latency", f"{A(1050,'ms_per_layer')/A(-1,'ms_per_layer')-1:+.1%}"),
    ]

    # --- the two-domain composition ---------------------------------------
    u = {r["quantity"]: float(r["value"])
         for r in csv.DictReader(open("data/two_domain_uncertainty.csv"))}
    checks += [
        ("scaling exponent", f"{u['exponent']:.2f}"),
        ("its combined sd", f"{u['combined_sd']:.2f}"),
        ("exponent max over all refits", f"{u['exponent_max_over_all_refits']:.2f}"),
    ]

    # --- cold vs hot, the quantity the whole design needed -----------------
    pk = [x for x in csv.DictReader(open("data/partition_kappa_qwen.csv"))
          if x["held"] == "True" and int(x["block_m"]) == 128]
    g = defaultdict(list)
    for x in pk:
        g[(x["part"], int(x["clock"]))].append(float(x["kappa_mw_per_mhz_per_sm"]))
    cls = sorted({int(x["clock"]) for x in pk})
    ratio = np.mean([np.mean(g[("light", c)]) / np.mean(g[("heavy", c)]) for c in cls])
    # 1.025 sits on a rounding boundary; quote three decimals so prose and
    # checker cannot disagree about which way it rounds
    checks += [("kappa ratio, cold over hot", f"{ratio:.3f}")]

    # --- the simulator (RESULTS_SIM.md) -------------------------------------
    # Its tables are generated by `python3 -m sim.report` from these files; a refit
    # changes them, so the document has to be re-pasted and this is what notices.
    import json
    if os.path.exists("sim/out/validation.json") and os.path.exists("sim/calib/a100_qwen.json"):
        cal = json.load(open("sim/calib/a100_qwen.json"))
        val = json.load(open("sim/out/validation.json"))
        m, r, pw = cal["meta"], cal["kernels"]["persistent"]["rate"], cal["power"]
        checks += [
            ("sim: rate fit, times", str(m["rate"]["all"]["n"])),
            ("sim: rate fit rms", f"{m['rate']['all']['rms']:.2f}%"),
            ("sim: cross-validation, holdout", f"{m['cross_validation'][m['form']]['sm_corun_holdout']['rms']:.2f}%"),
            ("sim: cross-validation, lowclk", f"{m['cross_validation'][m['form']]['sm_corun_lowclk']['rms']:.2f}%"),
            ("sim: power fit rms", f"{m['power']['all']['rms']:.2f}%"),
            ("sim: DRAM bandwidth", f"{r['bw_d']:.0f} GB/s"),
            ("sim: e_dram", f"{pw['e_dram'] * 1e3:.1f} mJ/GB"),
            ("sim: e_pad", f"{pw['e_pad']:.3f}"),
            ("sim: e_dram per clock, range",
             f"{min(m['power']['e_dram_per_clock_mj_gb']):.1f}-{max(m['power']['e_dram_per_clock_mj_gb']):.1f} mJ/GB"),
            ("sim: padding MAC / real MAC", f"{pw['e_pad'] / pw['e_mac'] * 100:.0f}%"),
            ("sim: pinned layer, time rms", f"{val['pinned_layer']['time']['rms']:.2f}%"),
            ("sim: ... pair swept side by side", f"{val['pinned_layer_seen']['time']['rms']:.2f}%"),
            ("sim: ... pair never swept", f"{val['pinned_layer_new']['time']['rms']:.2f}%"),
            ("sim: ... its worst case", f"{max(v['time']['rms'] for k, v in val.items() if k.startswith('pinned_layer_c')):.2f}%"),
            ("sim: pinned layer, power above idle", f"{val['pinned_layer']['power_dyn']['rms']:.2f}%"),
            ("sim: queue sweeps, time rms", f"{val['layer_queue_sweeps']['time']['rms']:.2f}%"),
            ("sim: queue kernel fit rms", f"{m['queue']['all']['rms']:.2f}%"),
            ("sim: rate parameters fitted", f"{m['rate']['free']} fitted"),
            ("sim: sd of the DRAM wait cost", f"{m['rate']['sigma']['aL'] * 100:.1f}%"),
            ("sim: q", f"{r['q']:.2f}"),
            ("sim: exponent of BW_L in the clock", f"clock^{r['gamma_l']:.2f}"),
            ("sim: exponent of xi in the clock", f"clock^{r['gamma_x']:.2f}"),
        ]
        for form, per in m["cross_validation"].items():
            for stem, cv in per.items():
                checks += [(f"sim: form {form}, {stem[9:]}", f"{cv['rms']:.2f}%")]
        for tag in ("heldout1", "heldout2"):               # the second shot; the first is in HELDOUT.md
            t = val["traces"][tag]
            checks += [(f"sim: {tag} second shot, latency", f"{t['latency_rms_pct']:.2f}%"),
                       (f"sim: {tag} second shot, clock", f"{t['clock_rms_mhz']:.1f} MHz"),
                       (f"sim: {tag} second shot, clock, same window", f"{t['clock_rms_mhz_same_window']:.1f} MHz"),
                       (f"sim: {tag} second shot, energy", ", ".join(f"{x:+.1f}%" for x in t["energy_err_pct"]))]
        for tag in ("dynamics", "trace", "trace2", "forward", "forward2"):
            t = val["traces"][tag]
            checks += [(f"sim: {tag} latency rms", f"{t['latency_rms_pct']:.2f}%"),
                       (f"sim: {tag} run energy", ", ".join(f"{x:+.1f}%" for x in t["energy_err_pct"])),
                       (f"sim: {tag} clock, same window", f"{t['clock_rms_mhz_same_window']:.1f} MHz"),
                       (f"sim: {tag} load step, replay by replay",
                        f"{t['transient_rms_pct']['load change']:.2f}%"),
                       (f"sim: {tag} highest reading, sim / measured",
                        f"{t['peak_reading_w']['sim']:.0f} / {t['peak_reading_w']['meas']:.0f} W")]
        if os.path.exists("sim/out/policies_trace2.csv"):
            pol = list(csv.DictReader(open("sim/out/policies_trace2.csv")))
            ref = pol[0]
            for key, lab in (("experts rebalanced per batch, one clock", "rebalanced, one clock"),
                             ("rebalanced, two domains, tdp_bisection", "rebalanced, two domains"),
                             ("fixed 1050 MHz", "fixed 1050 MHz")):
                x = next(r for r in pol if key in r["policy"])
                checks += [(f"sim: policies, {lab}: time",
                            f"{(float(x['busy_s']) / float(ref['busy_s']) - 1) * 100:+.1f}%"),
                           (f"sim: policies, {lab}: energy",
                            f"{(float(x['busy_j']) / float(ref['busy_j']) - 1) * 100:+.1f}%")]
        if os.path.exists("sim/out/policies_trace2_fixed.csv"):
            for x in csv.DictReader(open("sim/out/policies_trace2_fixed.csv")):
                checks += [(f"sim: fixed {x['clock']} MHz, measured energy", f"{float(x['meas_energy_pct']):+.1f}%"),
                           (f"sim: fixed {x['clock']} MHz, simulated energy", f"{float(x['sim_energy_pct']):+.1f}%"),
                           (f"sim: fixed {x['clock']} MHz, measured time", f"{float(x['meas_time_pct']):+.1f}%")]
        for m_ in ("olmoe", "granite", "qwen3next"):
            if f"xmodel_{m_}_solo" in val:
                checks += [(f"sim: {m_} solo, time rms", f"{val[f'xmodel_{m_}_solo']['time']['rms']:.2f}%")]
        worst47 = val["sm_corun_holdout_L47_qwen_corun"]["time"]["rms"]
        checks += [("sim: layer 47 co-run, time rms", f"{worst47:.2f}%")]
        g2048 = next(g for g in val["governor"] if g["tokens"] == 2048)
        checks += [("sim: governor at 2048 tokens (MHz)", f"{g2048['sim_clock']:.0f}")]
        st = {(x["objective"], x["name"]): x for x in csv.DictReader(open("sim/out/study_decode2048.csv"))}
        b0 = st[("fastest under TDP", "B0")]
        for obj, name in (("fastest under TDP", "B2"), ("fastest under TDP", "B4*"),
                          ("least energy, <= 1.02 x B0 latency", "B4*"),
                          ("least energy, <= 1.10 x B0 latency", "B1"),
                          ("least energy, <= 1.10 x B0 latency", "B4*"),
                          ("least energy, <= 1.25 x B0 latency", "B4")):
            x = st[(obj, name)]
            col = "ms" if obj.startswith("fastest") else "mj"
            checks += [(f"sim: 2048 {name}, {obj[:22]}",
                        f"{(float(x[col]) / float(b0[col]) - 1) * 100:+.1f}%")]
        # the second rail alone: B4* against B3*, every workload and target
        gap = []
        for stem in ("decode1024", "decode2048", "decode4096", "prefill"):
            T = {(x["objective"], x["name"]): x for x in csv.DictReader(open(f"sim/out/study_{stem}.csv"))}
            for obj in dict.fromkeys(k[0] for k in T):
                a, b = T[(obj, "B4*")], T[(obj, "B3*")]
                if a["ms"] and b["ms"] and not obj.startswith("fastest"):
                    gap.append((float(a["mj"]) / float(b["mj"]) - 1) * 100)
        checks += [("sim: second rail, energy, largest saving", f"{min(gap):+.2f}%"),
                   ("sim: second rail, energy, largest loss", f"{max(gap):+.2f}%")]
        for name in ("sensitivity_cells32_persistent.csv", "sensitivity_cells64_queue.csv"):
            rows = list(csv.DictReader(open(f"sim/out/{name}")))
            v = [float(x["energy_pct_1290"]) for x in rows]
            checks += [(f"sim: {name[12:19]}, as shipped", f"{v[0]:+.2f}%"),
                       (f"sim: {name[12:19]}, smallest saving", f"{max(v):+.2f}%"),
                       (f"sim: {name[12:19]}, largest saving", f"{min(v):+.2f}%")]
        gains = []
        for path in sorted(glob.glob("sim/out/boost_*.csv")):
            if path.endswith("_delay.csv"):
                continue
            B = defaultdict(dict)
            for x in csv.DictReader(open(path)):
                B[(x["wall"], x["n_cold"], x["cold_sms"])][x["policy"]] = float(x["ms"])
            gains += [(v["boost"] / v["per domain"] - 1) * 100 for v in B.values()]
        if gains:
            checks += [("sim: boost, largest gain anywhere", f"{min(gains):+.2f}%")]

    bad = 0
    print(f"{'quantity':>32s} {'from data':>12s}   quoted in a .md?")
    for name, got in checks:
        present = got in docs or got.lstrip("+") in docs
        if not present:
            bad += 1
        print(f"{name:>32s} {got:>12s}   {'yes' if present else 'NOT FOUND'}")

    # --- cross-references --------------------------------------------------
    figs = {os.path.basename(p)[:-4] for p in glob.glob("figs/*.png")}
    for f in sorted(glob.glob("*.md")):
        text = open(f).read()
        import re
        for fig in re.findall(r"figs/([A-Za-z0-9_]+)\.(?:pdf|png)", text):
            if fig not in figs:
                print(f"  BROKEN figure reference: {f} -> figs/{fig}"); bad += 1
        for s in re.findall(r"`([a-z0-9_]+\.py)`", text):
            if not os.path.exists(s) and not os.path.exists(f"vendor/{s}"):
                print(f"  BROKEN script reference: {f} -> {s}"); bad += 1
        # require a real extension: `data/routing_*.npz` is a glob, not a reference
        for d in re.findall(r"data/([A-Za-z0-9_.]+\.(?:csv|npz|json|txt))\b", text):
            if not os.path.exists(f"data/{d}"):
                print(f"  BROKEN data reference: {f} -> data/{d}"); bad += 1

    print("\nall consistent" if bad == 0 else f"\n{bad} problem(s)")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
